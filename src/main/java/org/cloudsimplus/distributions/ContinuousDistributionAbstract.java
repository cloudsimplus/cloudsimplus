package org.cloudsimplus.distributions;

import lombok.NonNull;
import org.apache.commons.rng.UniformRandomProvider;
import org.cloudsimplus.util.MathUtil;

/**
 * A base class for {@link ContinuousDistribution} implementations that generate random numbers
 * using a distribution from the <a href="https://commons.apache.org/proper/commons-statistics/">Apache Commons Statistics</a>
 * library.
 *
 * <p>In that library, a distribution object just computes the distribution properties
 * (such as {@link #getMean() mean} and {@link #density(double) density}),
 * while random numbers are generated by a separate
 * {@link org.apache.commons.statistics.distribution.ContinuousDistribution.Sampler Sampler}.
 * The sampler gets random numbers from a {@link UniformRandomProvider}
 * (a Pseudo-Random Number Generator, or PRNG, from the
 * <a href="https://commons.apache.org/proper/commons-rng/">Apache Commons RNG</a> library)
 * and transforms them to follow the distribution.
 * This class puts both objects together.</p>
 *
 * <p>Subclasses just need to provide the Commons Statistics distribution to use.</p>
 *
 * @author Manoel Campos da Silva Filho
 * @since CloudSim Plus 9.0.0
 */
public abstract class ContinuousDistributionAbstract implements ContinuousDistribution {
    /**
     * The distribution that computes the properties (mean, density, etc.) and creates the sampler.
     */
    private final org.apache.commons.statistics.distribution.ContinuousDistribution distribution;

    /**
     * The object that generates random numbers following the {@link #distribution}.
     */
    private final org.apache.commons.statistics.distribution.ContinuousDistribution.Sampler sampler;

    /** @see #getSeed() */
    private final long seed;

    /** @see #isApplyAntitheticVariates() */
    private boolean applyAntitheticVariates;

    /**
     * Creates a continuous distribution PRNG.
     *
     * @param distribution the Commons Statistics distribution to follow
     * @param seed the seed <b>already used</b> to initialize the PRNG
     * @param rng the actual Pseudo-Random Number Generator that will be the base
     *            to generate random numbers following the distribution
     * @throws IllegalArgumentException when the seed is negative
     */
    protected ContinuousDistributionAbstract(
        @NonNull final org.apache.commons.statistics.distribution.ContinuousDistribution distribution,
        final long seed, @NonNull final UniformRandomProvider rng)
    {
        this.distribution = distribution;
        this.seed = MathUtil.nonNegative(seed, "Seed");
        this.sampler = distribution.createSampler(rng);
    }

    @Override
    public double originalSample() {
        return sampler.sample();
    }

    @Override
    public long getSeed() {
        return seed;
    }

    @Override
    public boolean isApplyAntitheticVariates() {
        return applyAntitheticVariates;
    }

    @Override
    public ContinuousDistributionAbstract setApplyAntitheticVariates(final boolean applyAntitheticVariates) {
        this.applyAntitheticVariates = applyAntitheticVariates;
        return this;
    }

    @Override
    public double density(final double x) {
        return distribution.density(x);
    }

    @Override
    public double cumulativeProbability(final double x) {
        return distribution.cumulativeProbability(x);
    }

    @Override
    public double inverseCumulativeProbability(final double p) {
        return distribution.inverseCumulativeProbability(p);
    }

    @Override
    public double getMean() {
        return distribution.getMean();
    }

    @Override
    public double getVariance() {
        return distribution.getVariance();
    }

    @Override
    public double getSupportLowerBound() {
        return distribution.getSupportLowerBound();
    }

    @Override
    public double getSupportUpperBound() {
        return distribution.getSupportUpperBound();
    }
}
